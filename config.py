# -*- coding: utf-8 -*-
"""
config.py - 集中式硬件与通信配置

为什么要有这个文件
------------------
原工程把引脚号写散在三个文件里（main.py / stepper_motor.py / jg_cgq.py），
结果同一个引脚出现了互相矛盾的默认值：

    main.py          SERVO_PIN = 4   # 注释: 原 18 冲突，改为 4
    jg_cgq.py        SERVO_PIN = 18  # 自测块里没跟着改
    stepper_motor.py dir_pin   = 18  # 自测块里的 motor1

单独跑 jg_cgq.py 或 stepper_motor.py 的自测块时，舵机就会和"上下电机"的
DIR 脚撞在一起。现在所有引脚只在这里定义一次，改接线只改这个文件。

⚠️ 约束：下面所有引脚必须两两不同（BCM 编号）。
"""

# ---------------------------------------------------------------------------
# 步进电机（"使能 + 方向 + 脉冲"三线接法，如 TB6600 / DM542 驱动器）
# ---------------------------------------------------------------------------
MOTOR_UP_DOWN = dict(ena_pin=12, dir_pin=18, pul_pin=19, name="上下电机")
MOTOR_LEFT_RIGHT = dict(ena_pin=23, dir_pin=27, pul_pin=22, name="左右电机")
MOTOR_FWD_BACK = dict(ena_pin=6, dir_pin=25, pul_pin=5, name="前后电机")

# 一条串口指令驱动多少步（固定步长，无位置反馈）
STEPS_PER_COMMAND = 50

# 脉冲间隔（秒）。越小越快，但软件延时的抖动也越明显，高速下容易丢步。
PULSE_DELAY = 0.0001

# ---------------------------------------------------------------------------
# TCRT5000 红外对管 + 舵机夹爪
# ---------------------------------------------------------------------------
SENSOR_PIN = 17      # TCRT5000 的 OUT（数字量输出）
SERVO_PIN = 4        # 舵机信号线。⚠️ 不要用 18，那是"上下电机"的 DIR

GRAB_ANGLE = 20      # 夹紧角度
RELEASE_ANGLE = 90   # 松开角度
GRAB_TIME = 0.3      # 夹紧到位后额外等待时长（秒）
SERVO_SETTLE_S = 0.3  # 舵机转到目标角度后的稳定时间（秒）

# 夹取动作重复次数
# ⚠️ 原代码注释写"三次夹取动作"，实际是 range(5) 跑 5 次。
#    这里以代码的实际行为为准（5 次），只是把注释改正。
GRAB_REPEAT = 5
GRAB_PAUSE_S = 0.5     # 每次夹取之间的暂停时长（秒）
# 只有前 N 次夹取之后才暂停。原代码是硬编码的 `if i < 2`，
# 在 3 次循环里等于"最后一次不暂停"，但循环改成 5 次后就没跟着改，
# 属于复制粘贴残留。保持原行为（2），见 README「已知问题」。
GRAB_PAUSE_AFTER = 2

# 收到红外触发后，"前后电机"继续前进的步数
# ⚠️ 原代码注释写"延时0.2秒"，但 100 步 × (PULSE_DELAY × 2) ≈ 0.02 秒，
#    差一个数量级。这里保留原来的 100 步，不改变赛场上验证过的运动行为，
#    只把注释改正。若确实想延时 0.2 秒，把下方设为 0.2 即可。
POST_TRIGGER_STEPS = 100
POST_TRIGGER_DELAY_S = None   # None = 用走步代替延时；设成 0.2 = 真的延时 0.2 秒

# ---------------------------------------------------------------------------
# 串口（树莓派 <-> K230）
# ---------------------------------------------------------------------------
SERIAL_PORT = "/dev/ttyUSB0"
SERIAL_BAUDRATE = 115200
SERIAL_TIMEOUT = 0.1
SERIAL_READY_BYTE = 0xAA          # 树莓派 -> K230：我准备好了

# 收到 0xCC（K230 报告目标已居中）后是否退出主程序。
# True  = 干净收工（原代码完全没有处理这个字节，会被静默丢弃）
# False = 只停机、继续留在主循环里等后续指令
EXIT_ON_TARGET_CENTERED = True

# ---------------------------------------------------------------------------
# 串口指令表（K230 -> 树莓派），与 docs/protocol.md 保持一致
# ---------------------------------------------------------------------------
CMD_MOTOR2_FWD = 0x0C   # 左右电机 正转
CMD_MOTOR2_REV = 0x0B   # 左右电机 反转
CMD_MOTOR1_REV = 0x0D   # 上下电机 反转
CMD_MOTOR1_FWD = 0x0E   # 上下电机 正转
CMD_START_GRAB = 0xFF   # 启动"前后电机 + 红外触发夹取"流程（预留，比赛中未使用）
CMD_TARGET_CENTERED = 0xCC  # K230 报告目标已居中
